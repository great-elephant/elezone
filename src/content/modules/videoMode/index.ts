// ── Episode changes ───────────────────────────────────────────────────────────

// Both sites move between videos without a page load, so nothing would
// otherwise clear the previous title's cues — the sidebar would keep showing
// the wrong dialogue. Polling the URL is cheap and, unlike patching
// history.pushState, doesn't collide with the read-aloud SPA guard.
let _urlWatch: number | null = null

function watchForTitleChange() {
  if (_urlWatch !== null) return
  let lastUrl = location.href
  _urlWatch = window.setInterval(() => {
    // Cheap self-heal: both sites re-render around the player — Netflix after a
    // fullscreen transition, YouTube whenever it loads more recommendations —
    // which leaves the overlays parented to a node that is no longer on screen.
    if (_active) {
      reparentOverlays()
      syncLayoutMetrics()
    }
    if (location.href === lastUrl) return
    lastUrl = location.href
    if (!_active) return
    // Left the player entirely (browse, a title page, search). Tearing down is
    // the page watcher's job — rebuilding here would put the strip and sidebar
    // over a page that has no dialogue at all.
    if (!isPlaybackPage()) return
    _interceptorCues = []
    _domFallbackCues = []
    resetSubtitleInterceptor()
    clearNativeTranslationCues()
    clearPhoneticsCache()
    _verified = false
    _verifyHits = 0
    _verifyMisses = 0
    // The MAIN world clears its cache on the same URL change; ask it for the
    // new episode's tracks once it has them.
    requestSubtitleReplay(_targetLang, _learningLang)
    stopSubtitleSyncer()
    destroyDialogueSidebar()
    platform().showNativeSubtitles()
    buildUi()
    setSubtitleCardStatus(waitingStatus())
    updateSubtitleCard(null, _savedItems)
    installSubtitleDomParser(onDomCue, platform().nativeSubtitleSelectors)
  }, 1000)
}

// ── Settings updates (from popup toggles) ─────────────────────────────────────

export function applyVideoModeSettings(settings: VideoModeSettings): void {
  const prev = _settings
  _settings = { ...settings }
  if (!_active) return

  setSidebarVisible(_settings.sidebarVisible)
  syncLayoutMetrics()
  setSyncerAutoPause(_settings.pauseOnSavedWord)
  setTranslationSource(_settings.translationSource)
  setVideoModeKeysEnabled(_settings.keyboardShortcuts)
  applyPacingConfig()
  applySubtitleCardSettings({
    showTranslation: _settings.showTranslation,
    fontSize: _settings.subtitleFontSize,
    sidebarVisible: _settings.sidebarVisible,
    phoneticsUnderWords: _settings.phoneticsUnderWords,
    learningLang: _learningLang,
  })
  // Re-render the strip so the change lands on the line already on screen.
  updateSubtitleCard(getCurrentCue(), _savedItems)

  // These four change the cue list itself or how every row renders, and the
  // sidebar builds its rows up front — a restyle isn't enough.
  if (
    prev.showTranslation !== _settings.showTranslation ||
    prev.translationSource !== _settings.translationSource ||
    prev.hideSoundEffects !== _settings.hideSoundEffects ||
    prev.phoneticsUnderWords !== _settings.phoneticsUnderWords
  ) {
    if (_interceptorCues.length > 0) onCuesReady(_interceptorCues)
  }
}

// ── Detect if current site is a video platform ────────────────────────────────

export function isVideoSite(hostname = window.location.hostname): boolean {
  return platformFor(hostname) !== null
}

/**
 * Whether this URL is a page that actually plays something.
 *
 * Being on a video *site* is not enough: Netflix autoplays trailers on /browse
 * and /title, and YouTube plays them on the home feed, so a bare "is there a
 * <video>?" test turns the whole UI on over a grid of thumbnails — and, since
 * the strip and sidebar take space from the page, mangles its layout too.
 */
export function isPlaybackPage(url = window.location.href): boolean {
  return _platform?.isPlaybackPage(url) ?? false
}

/**
 * What is playing right now, or null when nothing is.
 *
 * The page watcher keys off this rather than a plain on-a-player-page test, so
 * that moving to another video is a distinct event. That matters because Video
 * Mode can shut itself down mid-page — a video with no subtitles in the language
 * being studied — and would otherwise never come back for the next one.
 */
export function playbackMediaKey(): string | null {
  if (!isPlaybackPage()) return null
  return _platform?.mediaKey() ?? 'playing'
}

// ── Wait for video element then try to init ───────────────────────────────────

/** Resolves once a <video> exists, or false if none turns up in time. */
export function waitForVideo(timeoutMs = 30_000): Promise<boolean> {
  if (document.querySelector('video')) return Promise.resolve(true)
  return new Promise(resolve => {
    let settled = false
    const finish = (found: boolean) => {
      if (settled) return
      settled = true
      observer.disconnect()
      clearTimeout(timer)
      resolve(found)
    }
    const observer = new MutationObserver(() => {
      if (document.querySelector('video')) finish(true)
    })
    observer.observe(document.documentElement, { childList: true, subtree: true })
    const timer = setTimeout(() => finish(false), timeoutMs)
  })
}
